def parse_xbrl(xbrl_path):
    """Parse XBRL file and return fact dictionaries keyed by local tag name."""
    tree = ET.parse(xbrl_path)
    root = tree.getroot()

    gaap_ns = NS["de-gaap-ci"]
    gcd_ns = NS["de-gcd"]
    xsi_nil = f"{{{NS['xsi']}}}nil"

    # Collect facts: {(local_name, contextRef): value}
    bs_current = {}  # contextRef="current_instant"
    bs_prior = {}    # contextRef="prior_instant"
    is_current = {}  # contextRef="current"
    is_prior = {}    # contextRef="prior"
    gcd_facts = {}   # de-gcd facts

    for elem in root.iter():
        tag = elem.tag
        ctx = elem.get("contextRef", "")
        is_nil = elem.get(xsi_nil, "false").lower() == "true"

        if tag.startswith(f"{{{gaap_ns}}}"):
            local = tag[len(f"{{{gaap_ns}}}"):]

            if is_nil:
                value = None
            else:
                try:
                    value = float(elem.text) if elem.text else None
                except (ValueError, TypeError):
                    value = None

            if local.startswith("bs."):
                if ctx == "current_instant":
                    bs_current[local] = value
                elif ctx == "prior_instant":
                    bs_prior[local] = value
            elif local.startswith("is."):
                if ctx == "current":
                    is_current[local] = value
                elif ctx == "prior":
                    is_prior[local] = value

        elif tag.startswith(f"{{{gcd_ns}}}"):
            local = "de-gcd:" + tag[len(f"{{{gcd_ns}}}"):]
            if ctx and not is_nil and elem.text:
                gcd_facts[local] = elem.text

    # Also search for nested GCD elements (some are inside tuple containers)
    for elem in root.iter():
        tag = elem.tag
        if tag.startswith(f"{{{gcd_ns}}}"):
            local = "de-gcd:" + tag[len(f"{{{gcd_ns}}}"):]
            ctx = elem.get("contextRef", "")
            is_nil = elem.get(xsi_nil, "false").lower() == "true"
            if ctx and not is_nil and elem.text and local not in gcd_facts:
                gcd_facts[local] = elem.text

    return bs_current, bs_prior, is_current, is_prior, gcd_facts


def write_stammdaten_sheet(wb, gcd_facts):
    """Write Stammdaten sheet with company info."""
    ws = wb.create_sheet("Stammdaten")

    company = gcd_facts.get("de-gcd:genInfo.company.id.name", "")
    ws.merge_cells("A1:B1")
    ws["A1"] = company
    ws["A1"].font = FONT_TITLE

    wj_von = gcd_facts.get("de-gcd:genInfo.report.period.fiscalYearBegin", "")
    wj_bis = gcd_facts.get("de-gcd:genInfo.report.period.fiscalYearEnd", "")
    ws.merge_cells("A2:B2")
    ws["A2"] = f"Wirtschaftsjahr {wj_von} bis {wj_bis}"
    ws["A2"].font = FONT_SMALL

    row = 4
    ws.cell(row=row, column=1, value="Feld").font = FONT_HEADER_WHITE
    ws.cell(row=row, column=2, value="Wert").font = FONT_HEADER_WHITE
    ws["A4"].fill = FILL_HEADER
    ws["B4"].fill = FILL_HEADER
    row = 5

    for gcd_path, label in STAMMDATEN_FIELDS:
        value = gcd_facts.get(gcd_path, "")
        ws.cell(row=row, column=1, value=label).font = FONT_BOLD
        ws.cell(row=row, column=2, value=value).font = FONT_NORMAL
        ws.cell(row=row, column=1).border = THIN_BORDER
        ws.cell(row=row, column=2).border = THIN_BORDER
        row += 1

    # HRB combined
    prefix = gcd_facts.get("de-gcd:genInfo.company.id.Incorporation.prefix", "")
    number = gcd_facts.get("de-gcd:genInfo.company.id.Incorporation.number", "")
    if prefix or number:
        for r in range(5, row):
            cell = ws.cell(row=r, column=1)
            if cell.value == "Handelsregister Präfix":
                cell.value = "Handelsregister"
                ws.cell(row=r, column=2, value=f"{prefix} {number}".strip())
                # Remove the separate number row
                break

    ws.column_dimensions["A"].width = 35
    ws.column_dimensions["B"].width = 40


def write_bilanz_sheet(wb, bs_current, bs_prior, gcd_facts):
    """Write Bilanz sheet with Aktiva and Passiva sections."""
    ws = wb.create_sheet("Bilanz")

    company = gcd_facts.get("de-gcd:genInfo.company.id.name", "")
    wj_bis = gcd_facts.get("de-gcd:genInfo.report.period.fiscalYearEnd", "")
    year = wj_bis[:4] if wj_bis else ""
    prev_year_end = gcd_facts.get("de-gcd:genInfo.report.period.balSheetClosingDatePreviousYear", "")
    prev_year = prev_year_end[:4] if prev_year_end else (str(int(year) - 1) if year else "Vorjahr")

    # Title
    ws.merge_cells("A1:D1")
    ws["A1"] = f"{company} — Bilanz zum {wj_bis}"
    ws["A1"].font = FONT_TITLE

    row = 3

    def write_section(section_name, mapping, start_row):
        r = start_row

        # Section header
        ws.merge_cells(f"A{r}:D{r}")
        ws.cell(row=r, column=1, value=section_name).font = FONT_HEADER
        ws.cell(row=r, column=1).border = BOTTOM_BORDER
        for c in range(2, 5):
            ws.cell(row=r, column=c).border = BOTTOM_BORDER
        r += 1

        # Column headers
        ws.cell(row=r, column=1, value="Position").font = FONT_HEADER_WHITE
        ws.cell(row=r, column=2, value="XBRL-Tag").font = FONT_HEADER_WHITE
        ws.cell(row=r, column=3, value=f"{year} EUR").font = FONT_HEADER_WHITE
        ws.cell(row=r, column=4, value=f"{prev_year} EUR").font = FONT_HEADER_WHITE
        for c in range(1, 5):
            ws.cell(row=r, column=c).fill = FILL_HEADER
            ws.cell(row=r, column=c).alignment = Alignment(horizontal="left")
        ws.cell(row=r, column=3).alignment = Alignment(horizontal="right")
        ws.cell(row=r, column=4).alignment = Alignment(horizontal="right")
        r += 1

        for tag_suffix, label, indent, is_summary in mapping:
            cur_val = bs_current.get(tag_suffix)
            pri_val = bs_prior.get(tag_suffix)

            indent_str = "  " * indent
            display_label = f"{indent_str}{label}"

            ws.cell(row=r, column=1, value=display_label).font = FONT_BOLD if is_summary else FONT_NORMAL
            ws.cell(row=r, column=2, value=tag_suffix).font = FONT_SMALL

            if cur_val is not None:
                cell_cur = ws.cell(row=r, column=3, value=cur_val)
                cell_cur.number_format = NUM_FMT
            else:
                ws.cell(row=r, column=3, value="—").font = FONT_SMALL

            if pri_val is not None:
                cell_pri = ws.cell(row=r, column=4, value=pri_val)
                cell_pri.number_format = NUM_FMT
            else:
                ws.cell(row=r, column=4, value="—").font = FONT_SMALL

            ws.cell(row=r, column=3).alignment = Alignment(horizontal="right")
            ws.cell(row=r, column=4).alignment = Alignment(horizontal="right")

            if is_summary and indent == 0:
                for c in range(1, 5):
                    ws.cell(row=r, column=c).fill = FILL_TOTAL
                    ws.cell(row=r, column=c).font = FONT_BOLD
                    ws.cell(row=r, column=c).border = BOTTOM_BORDER
            elif is_summary:
                for c in range(1, 5):
                    ws.cell(row=r, column=c).fill = FILL_SUMMARY
            else:
                for c in range(1, 5):
                    ws.cell(row=r, column=c).border = THIN_BORDER

            r += 1

        return r

    row = write_section("AKTIVA", BILANZ_AKTIVA, row)
    row += 1
    row = write_section("PASSIVA", BILANZ_PASSIVA, row)

    # Bilanz check row
    row += 1
    aktiva = bs_current.get("bs.ass")
    passiva = bs_current.get("bs.eqLiab")
    if aktiva is not None and passiva is not None:
        diff = aktiva - passiva
        ws.cell(row=row, column=1, value="Bilanzprüfung: Aktiva - Passiva").font = FONT_BOLD
        cell_diff = ws.cell(row=row, column=3, value=diff)
        cell_diff.number_format = NUM_FMT
        cell_diff.alignment = Alignment(horizontal="right")
        if abs(diff) >= 0.01:
            for c in range(1, 5):
                ws.cell(row=row, column=c).fill = FILL_ERROR
            ws.cell(row=row, column=1).font = FONT_ERROR
            cell_diff.font = FONT_ERROR
        else:
            ws.cell(row=row, column=1).font = FONT_BOLD
            cell_diff.font = FONT_BOLD

    ws.column_dimensions["A"].width = 55
    ws.column_dimensions["B"].width = 45
    ws.column_dimensions["C"].width = 18
    ws.column_dimensions["D"].width = 18


