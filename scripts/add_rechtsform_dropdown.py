#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Re-apply the Rechtsform dropdown (data validation) to the eBilanz template.

WHY THIS SCRIPT EXISTS
----------------------
The shipped workbook ``templates/ebilanz-template.xlsx`` is generated by
``tests/create_test_data.cpp`` (``createTemplate()``), which builds the file with
xlnt.  xlnt can *read* a worksheet that contains ``<dataValidations>`` -- its
consumer simply skips the element -- but it has no API and no serializer for
data validations at all, so it can never *write* one.

Consequence: every regeneration of the template silently drops the list
validation on ``Stammdaten!B6`` (Rechtsform) and the user loses the
``GmbH`` / ``UG (haftungsbeschränkt)`` dropdown together with its prompt and
error message.

This script re-applies that validation by patching the raw OOXML of the
worksheet part inside the .xlsx zip container.  It is idempotent, so it is safe
(and required) to run it after every ``create_test_data`` run::

    python scripts/add_rechtsform_dropdown.py [path/to/template.xlsx]

Only the standard library is used on purpose: the script must keep working in
build environments that have no openpyxl installed.
"""

import os
import re
import shutil
import sys
import tempfile
import zipfile

DEFAULT_TEMPLATE = os.path.join("templates", "ebilanz-template.xlsx")

#: Worksheet carrying the Rechtsform field.
SHEET_NAME = "Stammdaten"

#: Cell the dropdown is attached to.
TARGET_SQREF = "B6"

#: The validation element, exactly as Excel expects it.
VALIDATION_XML = (
    '<dataValidation type="list" errorStyle="stop" allowBlank="0"'
    ' showDropDown="0" showInputMessage="1" showErrorMessage="1"'
    ' promptTitle="Rechtsform"'
    ' prompt="GmbH: gezeichnetes Kapital mindestens 25.000 EUR.&#10;'
    'UG (haftungsbeschränkt): mindestens 1 EUR; gesetzliche Rücklage von'
    ' 25 % des Jahresüberschusses nach § 5a Abs. 3 GmbHG beachten."'
    ' errorTitle="Ungültige Rechtsform"'
    ' error="Bitte eine Rechtsform aus der Liste wählen:'
    ' GmbH oder UG (haftungsbeschränkt)."'
    ' sqref="' + TARGET_SQREF + '">'
    '<formula1>&quot;GmbH,UG (haftungsbeschränkt)&quot;</formula1>'
    "</dataValidation>"
)


class PatchError(Exception):
    """Raised when the workbook does not look like the expected template."""


# ---------------------------------------------------------------------------
# minimal XML element scanner
# ---------------------------------------------------------------------------

def _scan_start_tag(xml, pos):
    """Return (end_index, self_closing) for the start tag beginning at *pos*.

    Quoted attribute values are honoured, so a ``>`` inside an attribute does
    not terminate the tag prematurely.
    """
    i = pos
    quote = ""
    while i < len(xml):
        ch = xml[i]
        if quote:
            if ch == quote:
                quote = ""
        elif ch in ('"', "'"):
            quote = ch
        elif ch == ">":
            return i + 1, xml[i - 1] == "/"
        i += 1
    raise PatchError("unterminated start tag at offset %d" % pos)


def find_elements(xml, name):
    """Yield ``(start, end, start_tag)`` for every ``<name …>`` element."""
    pattern = re.compile(r"<%s(?=[\s/>])" % re.escape(name))
    closing = "</%s>" % name
    out = []
    for match in pattern.finditer(xml):
        start = match.start()
        tag_end, self_closing = _scan_start_tag(xml, start)
        if self_closing:
            end = tag_end
        else:
            close = xml.find(closing, tag_end)
            if close < 0:
                raise PatchError("missing %s" % closing)
            end = close + len(closing)
        out.append((start, end, xml[start:tag_end]))
    return out


# ---------------------------------------------------------------------------
# workbook part resolution
# ---------------------------------------------------------------------------

def resolve_sheet_part(archive, sheet_name):
    """Map a sheet name to its worksheet part path via workbook.xml(.rels)."""
    workbook = archive.read("xl/workbook.xml").decode("utf-8")
    rels = archive.read("xl/_rels/workbook.xml.rels").decode("utf-8")

    rel_id = None
    for _start, _end, tag in find_elements(workbook, "sheet"):
        name = re.search(r'\bname="([^"]*)"', tag)
        rid = re.search(r'\br:id="([^"]*)"', tag)
        if name and rid and name.group(1) == sheet_name:
            rel_id = rid.group(1)
            break
    if rel_id is None:
        raise PatchError('no sheet named "%s" in xl/workbook.xml' % sheet_name)

    for _start, _end, tag in find_elements(rels, "Relationship"):
        rid = re.search(r'\bId="([^"]*)"', tag)
        target = re.search(r'\bTarget="([^"]*)"', tag)
        if rid and target and rid.group(1) == rel_id:
            part = target.group(1)
            if part.startswith("/"):
                return part.lstrip("/")
            return "xl/" + part.lstrip("./")
    raise PatchError('relationship "%s" not found in workbook rels' % rel_id)


# ---------------------------------------------------------------------------
# sheet patching
# ---------------------------------------------------------------------------

def patch_sheet_xml(xml):
    """Insert/replace the B6 list validation. Returns ``(xml, action)``."""
    containers = find_elements(xml, "dataValidations")
    if len(containers) > 1:
        raise PatchError("worksheet has more than one <dataValidations> block")

    if containers:
        start, end, start_tag = containers[0]
        inner = xml[start + len(start_tag):end - len("</dataValidations>")]
        kept = []
        replaced = False
        for v_start, v_end, v_tag in find_elements(inner, "dataValidation"):
            if re.search(r'\bsqref="%s"' % re.escape(TARGET_SQREF), v_tag):
                replaced = True
                continue
            kept.append(inner[v_start:v_end])
        kept.append(VALIDATION_XML)
        block = '<dataValidations count="%d">%s</dataValidations>' % (
            len(kept),
            "".join(kept),
        )
        return xml[:start] + block + xml[end:], ("replaced" if replaced else "added")

    block = '<dataValidations count="1">%s</dataValidations>' % VALIDATION_XML

    # Schema order: <dataValidations> sits after <sheetData> and before
    # <pageMargins>.
    margins = re.search(r"<pageMargins(?=[\s/>])", xml)
    if margins:
        pos = margins.start()
    else:
        sheet_data = xml.find("</sheetData>")
        if sheet_data < 0:
            raise PatchError("worksheet has no </sheetData> element")
        pos = sheet_data + len("</sheetData>")
    return xml[:pos] + block + xml[pos:], "inserted"


# ---------------------------------------------------------------------------
# zip rewriting
# ---------------------------------------------------------------------------

def rewrite_archive(path, part, data):
    """Rewrite *path*, replacing only *part*; all other entries stay identical."""
    with zipfile.ZipFile(path, "r") as archive:
        infos = archive.infolist()
        payload = [(info, archive.read(info.filename)) for info in infos]
        comment = archive.comment

    handle, tmp = tempfile.mkstemp(
        suffix=".xlsx", dir=os.path.dirname(os.path.abspath(path)) or "."
    )
    os.close(handle)
    try:
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as out:
            out.comment = comment
            for info, blob in payload:
                if info.filename == part:
                    blob = data
                # Reuse the original ZipInfo: name, order, timestamp,
                # compression and attributes are preserved byte-for-byte.
                clone = zipfile.ZipInfo(info.filename, info.date_time)
                clone.compress_type = info.compress_type
                clone.external_attr = info.external_attr
                clone.internal_attr = info.internal_attr
                clone.create_system = info.create_system
                clone.comment = info.comment
                out.writestr(clone, blob)
        shutil.move(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)


def add_dropdown(path):
    if not os.path.isfile(path):
        raise PatchError("template not found: %s" % path)

    with zipfile.ZipFile(path, "r") as archive:
        part = resolve_sheet_part(archive, SHEET_NAME)
        try:
            original = archive.read(part).decode("utf-8")
        except KeyError:
            raise PatchError('worksheet part "%s" missing from %s' % (part, path))

    patched, action = patch_sheet_xml(original)
    if patched == original:
        return part, "unchanged"

    rewrite_archive(path, part, patched.encode("utf-8"))
    return part, action


def main(argv):
    path = argv[1] if len(argv) > 1 else DEFAULT_TEMPLATE
    try:
        part, action = add_dropdown(path)
    except (PatchError, zipfile.BadZipFile) as exc:
        sys.stderr.write("FEHLER: %s\n" % exc)
        return 1

    messages = {
        "inserted": "Rechtsform-Dropdown eingefuegt",
        "replaced": "Rechtsform-Dropdown ersetzt (war bereits vorhanden)",
        "added": "Rechtsform-Dropdown zu bestehenden Validierungen hinzugefuegt",
        "unchanged": "Rechtsform-Dropdown bereits aktuell - keine Aenderung",
    }
    print("%s: %s (%s!%s, %s)" % (messages[action], path, SHEET_NAME, TARGET_SQREF, part))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
